def _evaluation(cfg, *, step=1000, h=.960, e=2.2, scc=.95):
    identity = {k:cfg[k] for k in ('run_id','attempt','seed','dataset')}
    identity.update(completed_update=step,model_state_sha256='a'*64)
    rows = [{'scene_id':str(i),'raw_prediction_sha256':'b'*64} for i in range(20)]
    return {'qualification':{'metrics_complete':True,'metrics_finite':True,'same_state_verified':True},
        **{k:deepcopy(identity) for k in ('state_before','rr_state','fr_state','state_after')},
        'rr':{'metrics':{'ERGAS':e,'SCC':scc},'per_scene':deepcopy(rows)},
        'fr':{'metrics':{'HQNR':h},'per_scene':deepcopy(rows)}}


def _write_candidate(root, cfg, *, h=.960, e=2.2, scc=.95):
    directory = Path(root)/'runs'/cfg['run_id']/f"attempt_{cfg['attempt']:02d}"
    (directory/'models').mkdir(parents=True)
    # Non-pickle fixture: these tests exercise evidence/selection, not loading.
    checkpoint = directory/'models'/'step_0001000.pt'
    checkpoint.write_bytes(('checkpoint fixture '+cfg['run_id']).encode())
    evaluation = _evaluation(cfg,h=h,e=e,scc=scc)
    evaluation_path = directory/'evaluation_0001000.json'
    atomic_json(evaluation_path,evaluation)
    row,reasons = improvement(evaluation,{'best_selected':None,'best_hqnr':None})
    row.update(run_id=cfg['run_id'],attempt=cfg['attempt'],seed=cfg['seed'],
        checkpoint_path=str(checkpoint),file_sha256=file_sha(checkpoint),
        checkpoint_verified=True,metrics_complete=True,metrics_finite=True,same_state_verified=True,
        state_hash='a'*64,evaluation_path=str(evaluation_path),reasons=reasons)
    atomic_json(directory/'models'/'selection.json',{'saved':[row],
        'best_selected':row,'best_hqnr':row,'policy':plan.POLICY.manifest()})
    status = {'run_id':cfg['run_id'],'phase':'donor','attempt':cfg['attempt'],
        'status':'COMPLETED','step':plan.HORIZON,'directory':str(directory)}
    atomic_json(directory/'config.json',cfg)
    atomic_json(directory/'run_state.json',status)
    return status,row,evaluation


class FreshDonorEvidenceTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        c,r = plan.donor_queue()[0]
        self.cfg = plan.resolve_case('s4',c,r)

    def tearDown(self):
        self.temp.cleanup()

    def test_completed_fresh_candidate_accepts_saved_full40(self):
        run,row,_ = _write_candidate(self.root,self.cfg)
        found,rejected = fresh_candidates(self.root,[run])
        self.assertEqual(len(found),1)
        self.assertEqual(rejected,[])
        self.assertEqual(found[0]['file_sha256'],row['file_sha256'])
        self.assertEqual(found[0]['source_server'],'s4')

    def test_partial_and_unregistered_runs_are_not_candidates(self):
        run,_,_ = _write_candidate(self.root,self.cfg)
        run['status']='RUNNING'
        self.assertEqual(fresh_candidates(self.root,[run]),([],[]))
        run.update(status='COMPLETED',run_id='foreign_s1_donor')
        self.assertEqual(fresh_candidates(self.root,[run]),([],[]))

    def test_corrupt_checkpoint_or_fewer_scenes_is_rejected(self):
        run,row,evaluation = _write_candidate(self.root,self.cfg)
        Path(row['checkpoint_path']).write_bytes(b'changed')
        found,rejected = fresh_candidates(self.root,[run])
        self.assertFalse(found)
        self.assertTrue(rejected)
        evaluation['rr']['per_scene'].pop()
        atomic_json(row['evaluation_path'],evaluation)
        found,rejected = fresh_candidates(self.root,[run])
        self.assertFalse(found)
        self.assertIn('all20',rejected[0]['reason'])

    def test_scalar_evidence_disagreement_is_rejected(self):
        run,row,evaluation = _write_candidate(self.root,self.cfg)
        evaluation['rr']['metrics']['ERGAS']=1.0
        atomic_json(row['evaluation_path'],evaluation)
        found,rejected = fresh_candidates(self.root,[run])
        self.assertFalse(found)
        self.assertIn('scalar metrics',rejected[0]['reason'])

    def test_external_checkpoint_cannot_be_imported(self):
        outside = self.root/'not_a_campaign_donor.pt'
        outside.write_bytes(b'foreign')
        with self.assertRaisesRegex(ValueError,'generated by this s4'):
            verify_donor_file({'checkpoint_path':str(outside),'file_sha256':file_sha(outside)},
                              campaign_root=self.root)


class RuntimePolicyTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.campaign = Campaign(output=self.temp.name,device='cpu')
        self.campaign.state['timing']={'direct':{'update_p90':.16,'eval_seconds':20.,'checkpoint_seconds':10.},
            'stage2_gt':{'update_p90':.12,'eval_seconds':20.,'checkpoint_seconds':10.},
            'stage2_q':{'update_p90':.20,'eval_seconds':20.,'checkpoint_seconds':10.}}

    def tearDown(self):
        self.temp.cleanup()

    def test_selection_qualified_ergas_and_unqualified_hqnr_no_scc(self):
        c,r = plan.donor_queue()[0]
        cfg=plan.resolve_case('s4',c,r)
        first,_=improvement(_evaluation(cfg,h=.960,e=2.2,scc=.99),{})
        better,reasons=improvement(_evaluation(cfg,h=.9591,e=2.0,scc=.1),{'best_selected':first,'best_hqnr':first})
        self.assertIn('HQNR_GATE_ERGAS_SELECTOR',reasons)
        self.assertNotIn('BEST_HQNR_BACKUP',reasons)
        self.assertGreater(plan.rank(better),plan.rank(first))
        fallback,_=improvement(_evaluation(cfg,h=.958,e=1.5),{})
        self.assertGreater(plan.rank(first),plan.rank(fallback))

    def test_donor_admission_reserves_all_four_stage2_anchors(self):
        cfgs=[plan.resolve_case('s4',c,r) for c,r in plan.donor_queue()]
        estimate=self.campaign.estimate(cfgs[0])
        required=(3*estimate+4*2*estimate+600)*1.2
        with patch.object(self.campaign,'remaining_for_work',return_value=required-1):
            row=self.campaign.donor_admission(cfgs)
            self.assertEqual(row['status'],'REFUSED_INSUFFICIENT_CORE_BUDGET')
            self.assertAlmostEqual(row['estimated_seconds'],required)
        with patch.object(self.campaign,'remaining_for_work',return_value=required+1):
            self.assertEqual(self.campaign.donor_admission(cfgs)['status'],'ADMITTED')

    def test_measured_stage2_admission_requires_both_complete_pairs(self):
        groups=plan.stage2_groups()
        with patch.object(self.campaign,'remaining_for_work',return_value=1):
            row=self.campaign.stage2_anchor_admission(groups)
            self.assertEqual(row['status'],'REFUSED_INSUFFICIENT_CORE_BUDGET')
            self.assertEqual(row['pending_runs'],4)
        with self.assertRaisesRegex(ValueError,'complete preregistered'):
            self.campaign.stage2_anchor_admission(groups[1:])

    def test_donor_binding_refuses_any_incomplete_trio(self):
        with self.assertRaisesRegex(ValueError,'All three'):
            self.campaign.bind_donor()

    def test_insufficient_core_budget_never_starts_any_h50(self):
        with patch.object(self.campaign,'admission'), \
             patch.object(self.campaign,'preflight_cases'), \
             patch.object(self.campaign,'remaining_for_work',return_value=1), \
             patch.object(self.campaign,'run_case') as train, \
             patch.object(self.campaign,'bind_donor') as bind:
            result=self.campaign.run()
        self.assertEqual(result['status'],'STOPPED_BUDGET')
        self.assertIn('DONOR_TRIO_AND_FOUR_STAGE2',result['reason'])
        train.assert_not_called()
        bind.assert_not_called()

    def test_queue_binds_after_exactly_three_donors_then_shares_fixed_pair(self):
        seen=[]
        def train(cfg):
            if cfg['phase']=='stage2':
                self.assertEqual(self.campaign.state['donor']['checkpoint_sha256'],'f'*64)
            seen.append((cfg['phase'],cfg['case'],cfg['replica']))
            self.campaign.state['runs'].append({'run_id':cfg['run_id'],'status':'COMPLETED'})
        def bind():
            self.assertEqual(len(seen),3)
            self.assertTrue(all(row[0]=='donor' for row in seen))
            self.campaign.state['donor']={'checkpoint_sha256':'f'*64}
        with patch.object(self.campaign,'admission'), \
             patch.object(self.campaign,'preflight_cases'), \
             patch.object(self.campaign,'run_case',side_effect=train), \
             patch.object(self.campaign,'bind_donor',side_effect=bind):
            result=self.campaign.run()
        self.assertEqual(result['status'],'FINISHED_REGISTERED_QUEUE')
        self.assertEqual(len(seen),13)
        self.assertEqual([(c,r) for _,c,r in seen[:3]],plan.donor_queue())
        self.assertEqual(seen[3:7],[('stage2','G','R1'),('stage2','G','R2'),
                                    ('stage2','Q','R1'),('stage2','Q','R2')])

    def test_binding_selects_once_replays_and_preserves_same_pair(self):
        evals={}
        for index,(c,r) in enumerate(plan.donor_queue()):
            cfg=plan.resolve_case('s4',c,r)
            # Qualified second donor wins by E, not first donor's higher H/SCC.
            run,row,evaluation=_write_candidate(self.campaign.root,cfg,
                h=[.961,.9595,.958][index],e=[2.4,2.1,1.9][index],scc=[.99,.90,.99][index])
            self.campaign.state['runs'].append(run)
            evals[cfg['run_id']]=evaluation
        expected_cfg=plan.resolve_case('s4',*plan.donor_queue()[1])
        with patch('panda40.stage1.load_stage1_checkpoint',return_value=(object(),object(),{})), \
             patch.object(self.campaign,'evaluate',return_value=evals[expected_cfg['run_id']]):
            self.campaign.bind_donor()
        binding=deepcopy(self.campaign.state['donor'])
        self.assertEqual(binding['run_id'],expected_cfg['run_id'])
        self.assertFalse(binding['exploratory'])
        self.assertEqual(len(binding['required_donor_run_ids']),3)
        with patch('panda40.stage1.load_stage1_checkpoint',side_effect=AssertionError('must not reload')):
            self.campaign.bind_donor()
        self.assertEqual(self.campaign.state['donor'],binding)

    def test_binding_rejects_changed_aggregate_even_with_identical_per_scene(self):
        evaluations={}
        for index,(c,r) in enumerate(plan.donor_queue()):
            cfg=plan.resolve_case('s4',c,r)
            run,_,evaluation=_write_candidate(self.campaign.root,cfg,
                h=[.961,.9595,.958][index],e=[2.4,2.1,1.9][index])
            self.campaign.state['runs'].append(run)
            evaluations[cfg['run_id']]=evaluation
        expected_cfg=plan.resolve_case('s4',*plan.donor_queue()[1])
        original=evaluations[expected_cfg['run_id']]
        for split,key in (('rr','ERGAS'),('fr','HQNR')):
            altered=deepcopy(original)
            altered[split]['metrics'][key]+=.001
            with self.subTest(split=split), \
                 patch('panda40.stage1.load_stage1_checkpoint',return_value=(object(),object(),{})), \
                 patch.object(self.campaign,'evaluate',return_value=altered):
                with self.assertRaisesRegex(ValueError,'aggregate metric mismatch: '+split):
                    self.campaign.bind_donor()
            self.assertFalse((self.campaign.root/'fixed_donor.json').exists())
            self.assertNotIn('donor',self.campaign.state)


class CPUConstructionIntegrationTests(unittest.TestCase):
    """Real fresh Direct update -> frozen import -> Student update and reload.

    A tiny synthetic H5 is used; cost profiling alone is mocked. No checkpoint
    is portrayed as H50 or officially selectable, and no outbox is created.
    """
    @classmethod
    def setUpClass(cls):
        from panda_stage2_condq.tests.test_donor_sources import synthetic_sources
        cls.threads=torch.get_num_threads()
        torch.set_num_threads(1)
        cls.temp=tempfile.TemporaryDirectory()
        cls.fixture_root=Path(cls.temp.name)
        cls.registered=synthetic_sources(cls.fixture_root,count=12)
        with patch('pandas4.runtime.code_pin',return_value={'CPU_SYNTHETIC_ONLY':'a'*64}), \
             patch('pandas4.runtime.evaluator_identity',return_value={'CPU_SYNTHETIC_ONLY':'b'*64}):
            cls.campaign=Campaign(output=cls.fixture_root/'campaign',device='cpu')
        cls.campaign.sources=cls.registered.sources
        cls.campaign.registered=cls.registered
        cfg=plan.resolve_case('s4',*plan.donor_queue()[0])
        with patch('pandas4.cost.ensure_cost',return_value={'TEST_ONLY_NO_NUMERIC_COST':True}):
            trainer,stream=cls.campaign.build(cfg)
        cls.stage1_report,_=cls.campaign.trace(trainer,stream)
        cls.stage1_config=deepcopy(cfg)
        cls.stage1_path=cls.campaign.root/'synthetic_one_update_not_an_H50_donor.pt'
        cls.stage1_artifact=cls.campaign._save(trainer,stream,cls.stage1_path,cfg)
        cls.stage1_state_hash=cls.stage1_artifact['model_state_sha256']
        cls.campaign.state['donor']={'checkpoint_path':str(cls.stage1_path),
            'checkpoint_sha256':cls.stage1_artifact['file_sha256'],'exploratory':True}
        del trainer,stream

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()
        torch.set_num_threads(cls.threads)

    def build(self,case):
        cfg=plan.resolve_case('s4',case)
        with patch('pandas4.cost.ensure_cost',return_value={'TEST_ONLY_NO_NUMERIC_COST':True}) as cost:
            trainer,stream=self.campaign.build(cfg)
        cost.assert_called_once()
        self.assertEqual(trainer.config,cfg)
        return cfg,trainer,stream

    def test_actual_direct_H50_config_single_cpu_update_and_resume(self):
        from panda40.stage1 import load_stage1_checkpoint
        self.assertGreater(self.stage1_report['loss'],0.)
        trainer,stream,payload=load_stage1_checkpoint(self.stage1_path,
            self.stage1_artifact['file_sha256'],self.stage1_config,self.registered.sources,
            code_pin=self.campaign.code,evaluator_pin=self.campaign.evaluator_pin,
            restore_global_rng=False)
        self.assertEqual(trainer.updates,1)
        self.assertEqual(trainer.config['planned_horizon'],50000)
        self.assertEqual(trainer.effective_batch_size,48)
        self.assertTrue(payload['resume_only'])
        self.assertEqual(payload['state_hash'],self.stage1_state_hash)

    def test_all_real_stage2_constructions_keep_same_pair_seed_and_calibration_receipt(self):
        identities,initial=[],[]
        for case in plan.STAGE2:
            with self.subTest(case=case):
                cfg,trainer,stream=self.build(case)
                trainer.assert_contract(full_audit=True)
                identities.append(trainer.stage.donor_binding)
                initial.append(trainer.stage.student_initial_state_sha256)
                self.assertEqual(trainer.stage.spec.mask_policy,cfg['loss_mask_policy'])
                if case=='G':
                    self.assertIsNone(trainer.stage.teacher)
                    self.assertIsNone(cfg['calibration_sha256'])
                else:
                    receipt=json.loads(Path(cfg['calibration_path']).with_suffix('.json').read_text())
                    self.assertEqual(receipt['sha256'],receipt['file_sha256'])
                    self.assertEqual(receipt['sha256'],file_sha(cfg['calibration_path']))
                    self.assertEqual(receipt['donor_binding'],trainer.stage.donor_binding)
                    self.assertEqual(receipt['artifact_sha256'],trainer.stage.stats.artifact_sha256)
                del trainer,stream
        self.assertTrue(all(identity==identities[0] for identity in identities))
        self.assertEqual(len(set(initial)),1)
        masked=json.loads((self.campaign.root/'calibration'/'MASK2.json').read_text())
        full=json.loads((self.campaign.root/'calibration'/'FULL.json').read_text())
        self.assertLess(masked['n_e'],full['n_e'])
        self.assertEqual(masked['n_q'],full['n_q'])
        self.assertNotEqual(masked['artifact_sha256'],full['artifact_sha256'])

    def test_actual_student_48sample_update_checkpoint_restore_and_no_publication(self):
        from panda_stage2_condq.checkpoint import load_checkpoint
        cfg,trainer,stream=self.build('Q')
        report,_=self.campaign.trace(trainer,stream)
        self.assertEqual(trainer.updates,1)
        self.assertGreater(report['loss'],0.)
        trainer.assert_contract(full_audit=True)
        path=self.campaign.root/'synthetic_student_one_update.pt'
        artifact=self.campaign._save(trainer,stream,path,cfg)
        _,fresh,fresh_stream=self.build('Q')
        restored=load_checkpoint(path,artifact['sha256'],fresh)
        fresh_stream.load_state_dict(restored['stream_state'])
        self.assertEqual(fresh.updates,1)
        self.assertEqual(stream.state_dict(),fresh_stream.state_dict())
        self.assertEqual(fresh.stage.get_extra_state(),trainer.stage.get_extra_state())
        self.assertFalse((self.campaign.root/'outbox').exists())


